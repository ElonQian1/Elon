const fn edge(
    id: &'static str,
    from: SourceNodeId,
    to: SourceNodeId,
    kind: EdgeKind,
    epoch: Epoch,
    reachability: Reachability,
    effect: SourceEffect,
) -> SourceEdge {
    scoped_edge(id, from, to, kind, MAP_OPS, epoch, reachability, effect)
}

#[allow(clippy::too_many_arguments)]
const fn scoped_edge(
    id: &'static str,
    from: SourceNodeId,
    to: SourceNodeId,
    kind: EdgeKind,
    ops: &'static [PathOp],
    epoch: Epoch,
    reachability: Reachability,
    effect: SourceEffect,
) -> SourceEdge {
    SourceEdge {
        id,
        from,
        to,
        kind,
        ops,
        epoch,
        reachability,
        effect,
    }
}

