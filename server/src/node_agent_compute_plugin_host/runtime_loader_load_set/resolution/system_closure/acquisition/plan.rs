impl WindowsRecursiveSourceFrontierPlanEntry {
    pub(super) fn matches_receipt(
        &self,
        receipt: &WindowsPostLeaseSystemImageParseReceipt,
    ) -> bool {
        self.parse_receipt_ordinal == receipt.parse_receipt_ordinal
            && self.receipt_digest == receipt.receipt_digest
            && self.wave_ordinal == receipt.wave_ordinal
            && self.producer_acquisition_receipt_ordinal
                == receipt.producer_acquisition_receipt_ordinal
            && self.producer_module_request_ordinal == receipt.producer_module_request_ordinal
            && self.parsed_image_ordinal == receipt.parsed_image_ordinal
            && self.node == receipt.node
            && self.source_owner == receipt.source_owner
            && self.source_owner_binding_digest == receipt.source_owner_binding_digest
            && self.image_material_identity_digest == receipt.image_material_identity_digest
            && self.parser_policy_digest == receipt.parser_policy_digest
            && self.import_table_digest == receipt.import_table_digest
            && self.normal_import_count == receipt.normal_import_count
            && self.delay_import_count == receipt.delay_import_count
            && self.forwarder_count == receipt.forwarder_count
    }
}
