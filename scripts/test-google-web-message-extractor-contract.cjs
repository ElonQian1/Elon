const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const source = fs.readFileSync(
  path.join(root, 'android/app/src/main/assets/google_web_message_extractor.js'),
  'utf8',
)

assert.match(source, /const genericSelectors = \['body div'\]/)
assert.match(source, /'\[role="article"\]'/)
assert.match(source, /'body \[aria-live="polite"\]'/)
assert.match(source, /node\.closest\(/)
assert.match(source, /\[role="navigation"\]/)
assert.match(source, /\[role="dialog"\]/)
assert.match(source, /containsComposer\(node, composer\)/)
assert.match(source, /candidatePolicy\.accepts\(metrics\)/)
assert.match(source, /node\.matches\('\[aria-live\], \[role="status"\], \[role="alert"\]'\)/)
assert.match(source, /node\.querySelector\('\[aria-live\], \[role="status"\], \[role="alert"\]'\)/)
assert.match(source, /liveRegion,/)
assert.match(source, /\[role=\"tablist\"\]/)
assert.match(source, /const answer = query \? answerCandidate\(composer, query\) : null/)
assert.match(source, /hasQuery: !!query/)
assert.match(source, /queryPolicy\.select/)
assert.match(source, /headings\[headings\.length - 1\]/)
assert.match(source, /function hasCurrentQuery\(\)/)
assert.match(source, /function currentQueryMatches\(value\)/)
assert.match(source, /node\.checkVisibility/)
assert.match(source, /current\.getAttribute\('aria-hidden'\) === 'true'/)
assert.match(source, /current\.hasAttribute\('inert'\)/)
assert.match(source, /Number\(style\.opacity\) === 0/)
assert.doesNotMatch(source, /query \|\| location\.pathname === '\/search'/)
assert.doesNotMatch(source, /main h1, main \[role="heading"\]/)
assert.doesNotMatch(source, /document\.cookie|Authorization|fetch\(|outerHTML|sessionStorage|localStorage/)

console.log('google web message extractor contract passed')
