#[derive(PartialEq, Eq)]
pub(super) enum WindowsRecursiveFilesystemUseRoute {
    OrdinaryFilesystem,
    SideBySide,
}

/// Exact ultimate owner route. API-set is deliberately not a variant: it is a one-hop terminal
/// indirection to one of the system-owner variants below, so nested API-set resolution is
/// unrepresentable. Side-by-side remains an acquisition route for a filesystem owner, not a fifth
/// kind of immutable owner.
#[derive(PartialEq, Eq)]
pub(super) enum WindowsRecursiveRouteOwnerRef {
    PackageContentLease {
        package_file_ordinal: usize,
    },
    AuthenticatedPreloadedModule {
        preloaded_module_ordinal: usize,
    },
    KnownDllSection {
        known_dll_authority_record_ordinal: usize,
    },
    ResolvedFilesystemSystemImage {
        resolution_request_ordinal: usize,
        route: WindowsRecursiveFilesystemUseRoute,
    },
}

impl WindowsRecursiveRouteOwnerRef {
    pub(super) fn matches_image_owner(&self, owner: &WindowsRecursiveImageOwnerRef) -> bool {
        match (self, owner) {
            (
                Self::PackageContentLease {
                    package_file_ordinal: left,
                },
                WindowsRecursiveImageOwnerRef::PackageContentLease {
                    package_file_ordinal: right,
                },
            ) => left == right,
            (
                Self::AuthenticatedPreloadedModule {
                    preloaded_module_ordinal: left,
                },
                WindowsRecursiveImageOwnerRef::AuthenticatedPreloadedModule {
                    preloaded_module_ordinal: right,
                },
            ) => left == right,
            (
                Self::KnownDllSection {
                    known_dll_authority_record_ordinal: left,
                },
                WindowsRecursiveImageOwnerRef::KnownDllSection {
                    known_dll_authority_record_ordinal: right,
                },
            ) => left == right,
            (
                Self::ResolvedFilesystemSystemImage {
                    resolution_request_ordinal: left,
                    ..
                },
                WindowsRecursiveImageOwnerRef::ResolvedFilesystemSystemImage {
                    resolution_request_ordinal: right,
                },
            ) => left == right,
            _ => false,
        }
    }
}

