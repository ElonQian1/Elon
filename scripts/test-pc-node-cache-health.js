const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const routes = source('server/src/router/node_routes.rs')
const server = source('server/src/node_api/rust_cache_fleet/mod.rs')
const uploader = source('server/src/node_agent_rust_cache_fleet.rs')
const model = source('pc-frontend/src/features/node/nodeCacheHealth.ts')
const card = source('pc-frontend/src/features/node/NodeCacheHealthCard.tsx')
const cardStyles = source('pc-frontend/src/features/node/NodeCacheHealthCard.module.css')
const page = source('pc-frontend/src/features/node/NodePage.tsx')

assert.match(routes, /\/api\/node\/cache-reports\/:node_id/)
assert.match(routes, /\/api\/me\/nodes\/:node_id\/cache-reports\/latest/)
assert.match(server, /authenticate_node_bearer/)
assert.match(server, /destructive_actions_authorized:\s*false/)
assert.match(uploader, /secure_upload_origin/)
assert.match(uploader, /archive_accepted/)
assert.match(model, /encodeURIComponent\(nodeId\)/)
assert.match(model, /reason\.status === 404/)
assert.match(model, /response\.node_id !== expectedNodeId/)
assert.match(model, /response\.destructive_actions_authorized !== false/)
assert.match(model, /STALE_AFTER_MS = 24 \* 60 \* 60 \* 1000/)
assert.match(model, /报告已陈旧/)
assert.match(model, /报告异常/)
assert.match(card, /只读监控/)
assert.match(card, /尚未收到报告/)
assert.match(card, /缓存健康状态读取失败/)
assert.match(card, /报告不会授权远程删除/)
assert.doesNotMatch(`${model}\n${card}`, /api\.(post|put|patch|delete)\s*\(/i)
assert.doesNotMatch(card, /gc[^\n]*(apply|delete|purge)/i)
assert.match(cardStyles, /grid-template-columns:\s*repeat\(4, minmax\(0, 1fr\)\)/)
assert.match(cardStyles, /@media \(max-width: 760px\)/)
assert.match(cardStyles, /grid-template-columns:\s*repeat\(2, minmax\(0, 1fr\)\)/)
assert.match(page, /<NodeCacheHealthCard/)

console.log('PC node cache health contracts passed')

function source(relativePath) {
  return fs.readFileSync(path.join(root, relativePath), 'utf8')
}
