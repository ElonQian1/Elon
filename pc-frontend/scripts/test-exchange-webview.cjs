const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..', '..')
const read = (relativePath) => fs.readFileSync(path.join(root, relativePath), 'utf8')

const rust = read('desktop-shell/src-tauri/src/local_ai_browser.rs')
const providerCatalogRust = read('desktop-shell/src-tauri/src/local_ai_browser/provider_catalog.rs')
const exchangeRust = read('desktop-shell/src-tauri/src/local_ai_browser/exchange_webview.rs')
const main = read('desktop-shell/src-tauri/src/main.rs')
const permission = read('desktop-shell/src-tauri/permissions/exchange-web-session.toml')
const api = read('pc-frontend/src/features/exchange-webview/exchangeWebviewApi.ts')
const launcher = read('pc-frontend/src/features/exchange-webview/WindowsExchangeWebviewLaunch.tsx')
const preview = read('pc-frontend/src/features/plaza/OfficialProjectPreviewDialog.tsx')

assert.match(providerCatalogRust, /id: "binance"/)
assert.match(providerCatalogRust, /start_url: "https:\/\/www\.binance\.com\/zh-CN\/trading-bots\/futures\/grid\/NEARUSDT"/)
assert.match(providerCatalogRust, /allowed_hosts: &\["www\.binance\.com", "accounts\.binance\.com"\]/)
assert.match(providerCatalogRust, /adapter: None/)
assert.match(exchangeRust, /yilong\.exchange_webview\.provider\.v1/)
assert.match(exchangeRust, /ProviderKind::Exchange/)
assert.match(rust, /WindowEvent::Resized\(size\) => Some\(\*size\)/)
assert.match(rust, /WindowEvent::ScaleFactorChanged \{ new_inner_size, \.\. \} => Some\(\*new_inner_size\)/)
assert.match(rust, /page\.set_size\(size\)/)
assert.match(main, /list_exchange_web_providers/)
assert.match(main, /open_exchange_web_session/)
assert.match(permission, /list_exchange_web_providers/)
assert.match(permission, /open_exchange_web_session/)
assert.match(api, /REQUIRED_EXCHANGE_WEBVIEW_RUNTIME_VERSION = 12/)
assert.match(api, /list_exchange_web_providers/)
assert.match(api, /open_exchange_web_session/)
assert.match(launcher, /providerId !== launch\.provider_id/)
assert.match(launcher, /openingRef\.current/)
assert.match(launcher, /登录、验证和交易确认只在 Binance 官网完成/)
assert.match(preview, /preview\.windows_webview/)
assert.doesNotMatch(`${api}\n${launcher}`, /setInterval|setTimeout\(/)
assert.doesNotMatch(`${api}\n${launcher}`, /https:\/\/www\.binance\.com/)

console.log('Windows exchange WebView contracts passed')
