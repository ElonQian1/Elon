//! Public contract for external app tool quality reports.

use serde_json::{json, Value};

pub(crate) fn public_tool_quality_report_guidance(app_id: &str) -> Option<Value> {
    match app_id {
        "fb2" => Some(json!({
            "app_id": "fb2",
            "schema": "fb2.tool_quality_report.v1",
            "status": "available",
            "endpoint": {
                "method": "GET",
                "path": "/api/external/apps/fb2/tool-executions",
                "auth": {
                    "accepted_headers": [
                        "X-Elon-External-App-Token",
                        "Authorization: Bearer <external-app-service-token>"
                    ],
                    "scope": "own_app_only",
                    "service_token_env": [
                        "ELON_EXTERNAL_APP_FB2_TOKEN",
                        "ELON_EXTERNAL_APP_TOKEN"
                    ]
                }
            },
            "query": {
                "days": {
                    "type": "integer",
                    "default": 7,
                    "range": [1, 365],
                    "meaning": "统计最近多少天的 fb2 工具执行质量。"
                },
                "limit": {
                    "type": "integer",
                    "default": 50,
                    "range": [1, 500],
                    "meaning": "返回 recent_executions 的最大条数。"
                },
                "external_group_id": {
                    "type": "string",
                    "optional": true,
                    "meaning": "只看某个 fb2 群的工具执行记录。"
                },
                "status": {
                    "type": "string",
                    "optional": true,
                    "values": ["ready", "partial", "skipped", "unavailable", "not_configured"],
                    "meaning": "只看某类主项目执行状态。"
                }
            },
            "response_shape": {
                "schema": "external_app.tool_execution_report.v1",
                "summary": {
                    "total_executions": "integer",
                    "ready_executions": "integer",
                    "partial_executions": "integer",
                    "unavailable_executions": "integer",
                    "grounding_rate": "number",
                    "weak_rate": "number",
                    "unsafe_rate": "number",
                    "source_id_count": "integer",
                    "avg_duration_ms": "number"
                },
                "recent_executions": "array of metadata rows, newest first",
                "recommendations": "array of structured next actions generated by the main project",
                "privacy": {
                    "raw_payloads_exposed": false,
                    "raw_payloads_retained_in_table": "external_app_tool_executions"
                }
            },
            "recommendation_catalog": recommendation_catalog(),
            "agent_workflow": [
                "fb2 每次改动 /api/main-project/tools/execute 后，调用本报告观察最近 1-7 天 grounding/source/latency 趋势。",
                "如果 unsafe_result_count 大于 0，先修 visibility、permission 和 source_ids，再扩大 AI 自动采纳范围。",
                "如果 grounding_rate 偏低，优先让比赛、订单、群观点工具返回稳定 source ids。",
                "如果 avg_duration_ms 偏高，fb2 先加索引、缓存或收紧返回字段；主项目保持短超时和部分结果降级。",
                "该接口面向接入质量评估，不替代用户侧 AI 回复，也不对 ASR/TTS 或 context 拉取计费。"
            ]
        })),
        _ => None,
    }
}

