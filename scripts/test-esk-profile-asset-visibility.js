const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8')

const layout = read('android/app/src/main/res/layout/activity_main.xml')
const androidApi = read('android/app/src/main/kotlin/com/elon/app/esk/EskAssetApi.kt')
const androidCard = read('android/app/src/main/kotlin/com/elon/app/esk/EskAssetCard.kt')
const web = read('server/src/assets/web_page.html')

const profileTitle = layout.indexOf('android:id="@+id/profileAssetsTitle"')
const assetContainer = layout.indexOf('android:id="@+id/profileEskAssetContainer"')
const usageContainer = layout.indexOf('android:id="@+id/profileUsageContainer"')
assert.ok(profileTitle >= 0, 'Android profile must label the asset section')
assert.ok(assetContainer > profileTitle, 'Android ESK card must follow the asset section title')
assert.ok(usageContainer > assetContainer, 'Android ESK asset must appear before the tall Token quota card')
assert.match(layout, /android:text="我的资产"/)

assert.match(androidApi, /yilong\.esk\.asset_account\.v2/)
assert.match(androidApi, /reservedForSellback\s*=\s*exactAmount\(balance, "reserved_for_sellback"\)/)
assert.match(androidApi, /reservedForQuant\s*=\s*exactAmount\(balance, "reserved_for_quant"\)/)
assert.match(androidApi, /reservedTotal\s*=\s*exactAmount\(balance, "reserved_total"\)/)
assert.match(androidApi, /sellbackRequestEnabled\s*=\s*sellback\.optBoolean\("request_enabled"\)/)
assert.match(androidCard, /metric\("量化申请占用"\)/)
assert.match(androidCard, /metric\("全部申请占用"\)/)
assert.match(androidCard, /余额修订/)
assert.doesNotMatch(androidCard, /申请卖回 ESK[\s\S]{0,240}#4ADE80/)

const webTitle = web.indexOf('<h3 class="profile-section-title">我的资产</h3>')
const webAsset = web.indexOf('id="profileEskAssetCard"')
const webUsage = web.indexOf('<div class="usage-section">')
assert.ok(webTitle >= 0, 'Mobile Web profile must label the asset section')
assert.ok(webAsset > webTitle, 'Mobile Web ESK card must follow its title')
assert.ok(webUsage > webAsset, 'Mobile Web ESK asset must appear before Token quota')
assert.match(web, /api\('\/api\/me\/assets\/esk', \{ cache: 'no-store' \}\)/)
assert.match(web, /balance\.reserved_for_sellback/)
assert.match(web, /balance\.reserved_for_quant/)
assert.match(web, /balance\.reserved_total/)
assert.match(web, /snapshot\.schema !== 'yilong\.esk\.asset_account\.v2'/)
assert.match(web, /snapshot\.funds_moved/)
assert.match(web, /Number\.isInteger\(balance\.revision\)/)
assert.match(web, /登录后查看 ESK 资产/)
assert.match(web, /申请不代表成交或付款/)

console.log('ESK profile asset visibility contract passed')
