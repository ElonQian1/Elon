#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exposes_fb2_tool_quality_report_contract() {
        let contract = public_tool_quality_report_guidance("fb2").unwrap();
        assert_eq!(contract["schema"], "fb2.tool_quality_report.v1");
        assert_eq!(
            contract["endpoint"]["path"],
            "/api/external/apps/fb2/tool-executions"
        );
        assert_eq!(
            contract["response_shape"]["privacy"]["raw_payloads_exposed"],
            false
        );
        assert!(contract["recommendation_catalog"]
            .as_array()
            .unwrap()
            .iter()
            .any(|item| item["code"] == "low_grounding_rate"));
    }

    #[test]
    fn unknown_app_has_no_tool_quality_report_contract() {
        assert!(public_tool_quality_report_guidance("unknown").is_none());
    }
}
